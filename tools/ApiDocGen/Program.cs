using System.Reflection;
using System.Runtime.Loader;
using System.Text;
using System.Text.RegularExpressions;
using System.Xml.Linq;

// Generates the API reference pages from XenoUI assemblies + XML documentation comments.
if (args.Length < 2)
{
    Console.Error.WriteLine("usage: ApiDocGen <assembly directory> <output directory> [dependency directory...]");
    return 2;
}

// APIDOC_LANG=fr writes French labels (headings, table headers); the summaries come from the English source comments.
bool french = Environment.GetEnvironmentVariable("APIDOC_LANG") == "fr";
string T(string key) => !french ? key : key switch
{
    "API reference" => "Référence d’API", "Type" => "Type", "Kind" => "Genre", "Summary" => "Résumé",
    "Namespace" => "Espace de noms", "Types" => "Types", "Member" => "Membre", "Description" => "Description",
    "Value" => "Valeur", "Constructors" => "Constructeurs", "Properties" => "Propriétés", "Fields" => "Champs",
    "Methods" => "Méthodes", "Events" => "Événements", "Example" => "Exemple",
    "class" => "classe", "static class" => "classe statique", "abstract class" => "classe abstraite",
    "sealed class" => "classe scellée", "interface" => "interface", "struct" => "structure", "enum" => "énumération",
    _ => key
};
string KindText(Type t) => T(Kind(t));

string assemblyDirectory = Path.GetFullPath(args[0]);
string output = Path.GetFullPath(args[1]);
Directory.CreateDirectory(output);

// Load the XenoUI assemblies and resolve their dependencies (SkiaSharp...) from the same directory or from
// the extra directories given as further arguments (for example tools/DocSnippets/bin/Debug/net11.0).
AssemblyLoadContext.Default.Resolving += (context, name) =>
{
    foreach (string directory in new[] { assemblyDirectory }.Concat(args.Skip(2).Select(Path.GetFullPath)))
    {
        string candidate = Path.Combine(directory, name.Name + ".dll");
        if (File.Exists(candidate)) return context.LoadFromAssemblyPath(candidate);
    }
    return null;
};

var docs = new Dictionary<string, XElement>();
var assemblies = new List<Assembly>();
foreach (string dll in Directory.GetFiles(assemblyDirectory, "XenoUI.*.dll").OrderBy(f => f))
{
    string name = Path.GetFileNameWithoutExtension(dll);
    if (name.EndsWith(".Platforms") || name.EndsWith(".BuildTasks") || name.EndsWith(".Tooling")) continue;
    assemblies.Add(Assembly.LoadFrom(dll));
    string xml = Path.ChangeExtension(dll, ".xml");
    if (!File.Exists(xml)) continue;
    foreach (var member in XDocument.Load(xml).Descendants("member"))
        docs[(string)member.Attribute("name")!] = member;
}

// Engine internals (entity storage, slabs, systems) are public for the platform hosts only.
string[] InternalNamespaces = ["XenoUI.Core.Doddb", "XenoUI.Core.Memory", "XenoUI.Core.Pillars", "XenoUI.Core.Components.Primary"];

var types = assemblies.SelectMany(a => SafeTypes(a))
    .Where(t => t.IsPublic || t.IsNestedPublic)
    .Where(t => !t.IsDefined(typeof(System.Runtime.CompilerServices.CompilerGeneratedAttribute), false))
    .Where(t => t.Namespace != null && t.Namespace.StartsWith("XenoUI"))
    .Where(t => !InternalNamespaces.Contains(t.Namespace!))
    .OrderBy(t => t.Namespace).ThenBy(t => t.Name)
    .ToList();

var groups = types.GroupBy(t => t.Namespace!).OrderBy(g => g.Key).ToList();
var index = new StringBuilder();
index.AppendLine("# " + T("API reference"));
index.AppendLine();
index.AppendLine("<!-- Generated by tools/ApiDocGen from the XenoUI assemblies and their XML documentation comments. Do not edit by hand. -->");
index.AppendLine();
if (french)
{
    index.AppendLine("Types publics des bibliothèques XenoUI, générés à partir des commentaires du code source (en anglais). Pour les");
    index.AppendLine("explications et les exemples, commencez par le [guide développeur](../developer-guide.md) et [Créer un composant](../components.md).");
}
else
{
    index.AppendLine("Public types of the XenoUI libraries, generated from the source code comments. For explanations and examples, start");
    index.AppendLine("with the [developer guide](../developer-guide.md) and [Creating a component](../components.md).");
}
index.AppendLine();
index.AppendLine($"| {T("Namespace")} | {T("Types")} |");
index.AppendLine("|---|---|");

foreach (var group in groups)
{
    string file = Slug(group.Key) + ".md";
    index.AppendLine($"| [`{group.Key}`]({file}) | {group.Count()} |");
    var page = new StringBuilder();
    page.AppendLine($"# {group.Key}");
    page.AppendLine();
    page.AppendLine("<!-- Generated by tools/ApiDocGen. Do not edit by hand. -->");
    page.AppendLine();
    page.AppendLine($"[{T("API reference")}](index.md)");
    page.AppendLine();
    page.AppendLine($"| {T("Type")} | {T("Kind")} | {T("Summary")} |");
    page.AppendLine("|---|---|---|");
    foreach (var type in group)
        page.AppendLine($"| [`{DisplayName(type)}`](#{AnchorFor(type)}) | {KindText(type)} | {Cell(Summary(TypeId(type)))} |");
    page.AppendLine();
    foreach (var type in group) WriteType(page, type);
    File.WriteAllText(Path.Combine(output, file), Clean(page.ToString()));
}
File.WriteAllText(Path.Combine(output, "index.md"), Clean(index.ToString()));
Console.WriteLine($"{types.Count} types in {groups.Count} namespaces -> {output}");
return 0;

// ── Writing one type ────────────────────────────────────────────────────────────────────
void WriteType(StringBuilder page, Type type)
{
    page.AppendLine($"## `{DisplayName(type)}` {{ #{AnchorFor(type)} }}");
    page.AppendLine();
    page.AppendLine($"`{TypeDeclaration(type)}`");
    page.AppendLine();
    string summary = Summary(TypeId(type));
    if (summary.Length > 0) { page.AppendLine(summary); page.AppendLine(); }
    string remarks = Section(TypeId(type), "remarks");
    if (remarks.Length > 0) { page.AppendLine(remarks); page.AppendLine(); }
    string example = Example(TypeId(type));
    if (example.Length > 0) { page.AppendLine(example); page.AppendLine(); }

    var flags = BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly;
    if (type.IsEnum)
    {
        page.AppendLine($"| {T("Value")} | {T("Description")} |");
        page.AppendLine("|---|---|");
        foreach (var field in type.GetFields(flags).Where(f => f.IsLiteral))
            page.AppendLine($"| `{field.Name}` | {Cell(Summary($"F:{TypeId(type)[2..]}.{field.Name}"))} |");
        page.AppendLine();
        return;
    }

    Table(page, T("Constructors"), type.GetConstructors(BindingFlags.Public | BindingFlags.Instance)
        .Select(c => (Sig: $"{DisplayName(type)}({Parameters(c.GetParameters())})", Doc: MethodDoc(type, c, ".#ctor"))));
    Table(page, T("Properties"), type.GetProperties(flags).Where(p => p.GetMethod?.IsPublic == true || p.SetMethod?.IsPublic == true)
        .Where(p => p.GetIndexParameters().Length == 0)
        .Select(p => (Sig: $"{TypeName(p.PropertyType)} {p.Name} {{ {(p.GetMethod?.IsPublic == true ? "get; " : "")}{(p.SetMethod?.IsPublic == true ? "set; " : "")}}}",
                      Doc: Summary($"P:{TypeId(type)[2..]}.{p.Name}"))));
    Table(page, T("Fields"), type.GetFields(flags).Where(f => !f.IsSpecialName)
        .Select(f => (Sig: $"{(f.IsStatic ? "static " : "")}{(f.IsInitOnly ? "readonly " : "")}{TypeName(f.FieldType)} {f.Name}",
                      Doc: Summary($"F:{TypeId(type)[2..]}.{f.Name}"))));
    Table(page, T("Methods"), type.GetMethods(flags).Where(m => !m.IsSpecialName)
        .Select(m => (Sig: MethodSignature(m), Doc: MethodDoc(type, m, "." + m.Name))));
    Table(page, T("Events"), type.GetEvents(flags)
        .Select(e => (Sig: $"event {TypeName(e.EventHandlerType!)} {e.Name}", Doc: Summary($"E:{TypeId(type)[2..]}.{e.Name}"))));
}

void Table(StringBuilder page, string title, IEnumerable<(string Sig, string Doc)> rows)
{
    var list = rows.OrderBy(r => r.Sig, StringComparer.Ordinal).ToList();
    if (list.Count == 0) return;
    page.AppendLine($"**{title}**");
    page.AppendLine();
    page.AppendLine($"| {T("Member")} | {T("Description")} |");
    page.AppendLine("|---|---|");
    foreach (var (sig, doc) in list) page.AppendLine($"| `{Escape(sig)}` | {Cell(doc)} |");
    page.AppendLine();
}

// ── XML documentation lookup ────────────────────────────────────────────────────────────
string TypeId(Type t) => "T:" + XmlTypeName(t);

string XmlTypeName(Type t) => (t.FullName ?? t.Name).Replace('+', '.');

string Summary(string id) => docs.TryGetValue(id, out var m) ? Render(m.Element("summary")) : "";

string Section(string id, string element) => docs.TryGetValue(id, out var m) ? Render(m.Element(element)) : "";

string Example(string id)
{
    if (!docs.TryGetValue(id, out var m) || m.Element("example") is not { } example) return "";
    return "**Example**\n\n" + Render(example);
}

// Overloads share a name: choose the documented overload with the same parameter count and, if
// several, the best match on parameter type names.
string MethodDoc(Type type, MethodBase method, string nameSuffix)
{
    string prefix = "M:" + XmlTypeName(type) + nameSuffix;
    var parameters = method.GetParameters();
    XElement? best = null;
    int bestScore = -1;
    foreach (var (key, element) in docs)
    {
        if (!key.StartsWith(prefix, StringComparison.Ordinal)) continue;
        string rest = key[prefix.Length..];
        string name = rest.Split('(')[0];
        if (rest.Length > 0 && rest[0] != '(' && !name.StartsWith("``")) continue;
        var keyParameters = rest.Contains('(') ? SplitParameters(rest[(rest.IndexOf('(') + 1)..^1]) : [];
        if (keyParameters.Count != parameters.Length) continue;
        int score = 0;
        for (int i = 0; i < parameters.Length; i++)
            if (ShortName(keyParameters[i]) == ShortName(XmlParameterType(parameters[i].ParameterType))) score++;
        if (score > bestScore) { best = element; bestScore = score; }
    }
    return best == null ? "" : Render(best.Element("summary"));
}

static List<string> SplitParameters(string text)
{
    var result = new List<string>();
    int depth = 0, start = 0;
    for (int i = 0; i < text.Length; i++)
    {
        if (text[i] is '{' or '(') depth++;
        else if (text[i] is '}' or ')') depth--;
        else if (text[i] == ',' && depth == 0) { result.Add(text[start..i]); start = i + 1; }
    }
    if (text.Length > 0) result.Add(text[start..]);
    return result;
}

static string ShortName(string xmlType)
{
    string t = Regex.Replace(xmlType, @"\{.*\}", "");
    t = t.TrimEnd('@', '*').Replace("[]", "");
    int dot = t.LastIndexOf('.');
    return (dot >= 0 ? t[(dot + 1)..] : t).Replace("`", "");
}

static string XmlParameterType(Type t)
{
    if (t.IsByRef) t = t.GetElementType()!;
    if (t.IsArray) return XmlParameterType(t.GetElementType()!) + "[]";
    if (t.IsGenericParameter) return "`" + t.GenericParameterPosition;
    return (t.FullName ?? t.Name).Replace('+', '.');
}

// ── Rendering XML to Markdown ───────────────────────────────────────────────────────────
string Render(XElement? element)
{
    if (element == null) return "";
    var sb = new StringBuilder();
    foreach (var node in element.Nodes()) RenderNode(node, sb);
    return Regex.Replace(sb.ToString().Trim(), @"[ \t]+\n", "\n");
}

void RenderNode(XNode node, StringBuilder sb)
{
    switch (node)
    {
        case XText text:
            sb.Append(Regex.Replace(HtmlEscape(text.Value), @"\s+", " "));
            break;
        case XElement e:
            switch (e.Name.LocalName)
            {
                case "see" or "seealso":
                    string cref = (string?)e.Attribute("cref") ?? (string?)e.Attribute("langword") ?? "";
                    sb.Append('`').Append(CrefName(cref)).Append('`');
                    break;
                case "paramref" or "typeparamref":
                    sb.Append('`').Append((string?)e.Attribute("name")).Append('`');
                    break;
                case "c":
                    sb.Append('`').Append(e.Value).Append('`');
                    break;
                case "code":
                    sb.Append("\n\n```csharp\n").Append(Dedent(e.Value)).Append("\n```\n\n");
                    break;
                case "para":
                    sb.Append("\n\n");
                    foreach (var child in e.Nodes()) RenderNode(child, sb);
                    sb.Append("\n\n");
                    break;
                case "list":
                    foreach (var item in e.Elements("item"))
                    {
                        sb.Append("\n- ");
                        foreach (var child in (item.Element("description") ?? item).Nodes()) RenderNode(child, sb);
                    }
                    sb.Append('\n');
                    break;
                default:
                    foreach (var child in e.Nodes()) RenderNode(child, sb);
                    break;
            }
            break;
    }
}

static string CrefName(string cref)
{
    if (cref.Length > 2 && cref[1] == ':') cref = cref[2..];
    cref = Regex.Replace(cref, @"\(.*\)", "");
    int generic = cref.IndexOf('{');
    if (generic >= 0) cref = cref[..generic];
    int dot = cref.LastIndexOf('.');
    string name = dot >= 0 ? cref[(dot + 1)..] : cref;
    return name.Replace("`", "");
}

static string Dedent(string code)
{
    var lines = code.Replace("\r\n", "\n").Trim('\n').Split('\n');
    int indent = lines.Where(l => l.Trim().Length > 0).Select(l => l.Length - l.TrimStart().Length).DefaultIfEmpty(0).Min();
    return string.Join("\n", lines.Select(l => l.Length >= indent ? l[indent..] : l.TrimStart())).TrimEnd();
}

// Text outside code: neutralise HTML, the Markdown table separator, and Jinja markers (the site uses macros).
static string HtmlEscape(string text) => text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

static string Cell(string markdown)
{
    string single = Regex.Replace(markdown.Replace("\r", ""), @"\n+", " ").Replace("|", "\\|");
    return Clean(single);
}

static string Escape(string code) => code.Replace("|", "\\|");

static string Clean(string text) => text.Replace("{{", "&#123;&#123;").Replace("{%", "&#123;%");

// ── C# formatting of types and members ──────────────────────────────────────────────────
static IEnumerable<Type> SafeTypes(Assembly a)
{
    try { return a.GetTypes(); }
    catch (ReflectionTypeLoadException e) { return e.Types.Where(t => t != null)!; }
}

static string Slug(string ns) => ns.ToLowerInvariant().Replace('.', '-');

static string Kind(Type t) => t.IsEnum ? "enum" : t.IsInterface ? "interface" : t.IsValueType ? "struct"
    : t.IsAbstract && t.IsSealed ? "static class" : t.IsAbstract ? "abstract class" : t.IsSealed ? "sealed class" : "class";

static string DisplayName(Type t)
{
    string name = t.Name;
    int tick = name.IndexOf('`');
    if (tick >= 0) name = name[..tick] + "<" + string.Join(", ", t.GetGenericArguments().Select(a => a.Name)) + ">";
    return t.IsNested ? DisplayName(t.DeclaringType!) + "." + name : name;
}

static string AnchorFor(Type t) => Regex.Replace(DisplayName(t).ToLowerInvariant(), @"[^a-z0-9]+", "-").Trim('-') + "-" + Kind(t).Replace(' ', '-');

static string TypeDeclaration(Type t)
{
    var parts = new List<string> { "public", Kind(t) };
    string baseText = "";
    var inherits = new List<string>();
    if (t.BaseType != null && t.BaseType != typeof(object) && t.BaseType != typeof(ValueType) && t.BaseType != typeof(Enum))
        inherits.Add(TypeName(t.BaseType));
    inherits.AddRange(t.GetInterfaces().Where(i => t.BaseType == null || !t.BaseType.GetInterfaces().Contains(i)).Select(TypeName));
    if (inherits.Count > 0) baseText = " : " + string.Join(", ", inherits);
    return string.Join(' ', parts) + " " + DisplayName(t) + baseText;
}

static string MethodSignature(MethodInfo m)
{
    string generics = m.IsGenericMethodDefinition ? "<" + string.Join(", ", m.GetGenericArguments().Select(a => a.Name)) + ">" : "";
    string modifiers = (m.IsStatic ? "static " : "") + (m.IsAbstract && !m.DeclaringType!.IsInterface ? "abstract " : m.IsVirtual && !m.IsFinal && !m.DeclaringType!.IsInterface ? "virtual " : "");
    return $"{modifiers}{TypeName(m.ReturnType)} {m.Name}{generics}({Parameters(m.GetParameters())})";
}

static string Parameters(ParameterInfo[] parameters) => string.Join(", ", parameters.Select(p =>
{
    string prefix = p.IsOut ? "out " : p.ParameterType.IsByRef ? (p.IsIn ? "in " : "ref ") : "";
    if (p.GetCustomAttribute<ParamArrayAttribute>() != null) prefix = "params ";
    string type = TypeName(p.ParameterType.IsByRef ? p.ParameterType.GetElementType()! : p.ParameterType);
    string text = $"{prefix}{type} {p.Name}";
    if (p.HasDefaultValue)
        text += " = " + (p.DefaultValue switch { null => "null", string s => $"\"{s}\"", bool b => b ? "true" : "false", var v => v.ToString() });
    return text;
}));

static string TypeName(Type t)
{
    if (t.IsByRef) return TypeName(t.GetElementType()!);
    if (t.IsArray) return TypeName(t.GetElementType()!) + "[]";
    if (t.IsGenericParameter) return t.Name;
    if (Nullable.GetUnderlyingType(t) is { } underlying) return TypeName(underlying) + "?";
    string? keyword = Type.GetTypeCode(t) switch
    {
        TypeCode.Boolean => "bool", TypeCode.Byte => "byte", TypeCode.SByte => "sbyte", TypeCode.Char => "char",
        TypeCode.Decimal => "decimal", TypeCode.Double => "double", TypeCode.Single => "float", TypeCode.Int16 => "short",
        TypeCode.Int32 => "int", TypeCode.Int64 => "long", TypeCode.UInt16 => "ushort", TypeCode.UInt32 => "uint",
        TypeCode.UInt64 => "ulong", TypeCode.String => "string", _ => null
    };
    if (keyword != null) return keyword;
    if (t == typeof(void)) return "void";
    if (t == typeof(object)) return "object";
    string name = t.Name;
    int tick = name.IndexOf('`');
    if (t.IsGenericType)
    {
        string baseName = tick >= 0 ? name[..tick] : name;
        return baseName + "<" + string.Join(", ", t.GetGenericArguments().Select(TypeName)) + ">";
    }
    return t.IsNested ? TypeName(t.DeclaringType!) + "." + name : name;
}
